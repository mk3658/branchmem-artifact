def build() -> dict:
    families = []
    for fam in FAMILIES:
        items = []
        for t in TYPES:
            spec = fam["items"][t]
            items.append({
                "type": t,
                "predicate": spec["predicate"],
                "ancestor_value": spec["ancestor"],
                "update_value": spec["update"],
                "keep_value": spec["keep"],
                "correct_action": CORRECT[t],
                "domain": fam["domain"],
                "family": fam["family"],
            })
        families.append({"family": fam["family"], "domain": fam["domain"], "items": items})
    n = sum(len(f["items"]) for f in families)
    return {
        "note": (
            "BranchMem-Hard. Standing rules whose force is NOT recoverable from surface "
            "wording: types standing_indefinite, standing_expired, "
            "standing_conditional_unmet and standing_waived all carry an "
            "obligation-bearing ancestor in the same register, and only the first makes "
            "rejecting the update correct. A policy that reads 'this ancestor sounds "
            "like a rule' as 'reject the update' is therefore right on one type in four "
            "and freezes legitimate updates on the other three. Built because the modal "
            "marker in data/discrimination_bank.json fires on 80/80 constraint ancestors "
            "and 0/80 override ancestors, so that bank cannot measure DETECTION. "
            "Hand-authored by the authors against the specification in "
            "scripts/author_hard_standing_bank.py; synthetic, not sampled from any "
            "corpus, and not generated by any model evaluated on it."
        ),
        "types": list(TYPES),
        "correct_action_by_type": CORRECT,
        "n_items": n,
        "n_families": len(families),
        "families": families,
    }


def main() -> None:
    payload = build()
    OUT.write_text(json.dumps(payload, indent=2))
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    (OUT.parent / "hard_standing_bank.sha256").write_text(f"{digest}  {OUT.name}\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {payload['n_items']} items, "
          f"{payload['n_families']} families, {len(TYPES)} types")
    print("sha256", digest)


if __name__ == "__main__":
    main()
