"""Author BranchMem-Hard: standing rules whose force is NOT a surface cue.

Why this bank exists. In `data/discrimination_bank.json` the two critical types
are separable by a free regex: a modal/obligation marker fires on 80/80
constraint ancestors and 0/80 override ancestors, a property the bank's own
validator asserts. That makes the bank sound for the question it was built for
-- can a merger ACT on the distinction when the metadata is uninformative --
but useless for the question this bank is built for: can a merger DETECT when
the distinction is at stake, with no planted cue to key on.

So every item of types 1-4 below carries an obligation-bearing ancestor in the
same register, and what separates them sits elsewhere:

  standing_indefinite        in force until explicitly withdrawn; the update
                             violates it                       -> KEEP
  standing_expired           the ancestor states its own end; the update
                             reports the state after it         -> UPDATE
  standing_conditional_unmet the ancestor binds only under a condition the
                             update shows does not hold         -> UPDATE
  standing_waived            the ancestor is a third party's rule and the
                             update reports that party's waiver -> UPDATE
  ordinary_value             no obligation at all; a stale value corrected,
                             the control type                   -> UPDATE

A policy that treats "the ancestor sounds like a rule" as "reject the update"
is therefore right on type 1 and wrong on types 2-4. That is the freezing cost
the paper needs to quantify, and no lexical shortcut recovers it.

Authored by the authors against this specification, not generated by any model
evaluated on it, and declared synthetic. Validators in
`tests/test_hard_standing_bank.py` enforce the no-cue property rather than
asking the reader to trust it.

Usage: PYTHONPATH=. python scripts/author_hard_standing_bank.py
"""
